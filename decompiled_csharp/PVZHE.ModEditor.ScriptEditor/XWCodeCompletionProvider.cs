using System.Collections.Generic;
using System.ComponentModel;
using Godot;
using Godot.Bridge;
using Godot.NativeInterop;

namespace PVZHE.ModEditor.ScriptEditor;

[ScriptPath("res://addons/ModEditor/ScriptEditor/Completion/XWCodeCompletionProvider.cs")]
public abstract class XWCodeCompletionProvider : RefCounted
{
	public new class MethodName : RefCounted.MethodName
	{
		public static readonly StringName RequestCompletion = "RequestCompletion";
	}

	public new class PropertyName : RefCounted.PropertyName
	{
		public static readonly StringName CodeEdit = "CodeEdit";
	}

	public new class SignalName : RefCounted.SignalName
	{
	}

	protected readonly CodeEdit CodeEdit;

	protected XWCodeCompletionProvider(CodeEdit codeEdit)
	{
		CodeEdit = codeEdit;
	}

	public virtual void RequestCompletion()
	{
		CodeEdit?.UpdateCodeCompletionOptions(force: true);
	}

	[EditorBrowsable(EditorBrowsableState.Never)]
	internal static List<MethodInfo> GetGodotMethodList()
	{
		return new List<MethodInfo>(1)
		{
			new MethodInfo(MethodName.RequestCompletion, new PropertyInfo(Variant.Type.Nil, "", PropertyHint.None, "", PropertyUsageFlags.Default, exported: false), MethodFlags.Normal, null, null)
		};
	}

	[EditorBrowsable(EditorBrowsableState.Never)]
	protected override bool InvokeGodotClassMethod(in godot_string_name method, NativeVariantPtrArgs args, out godot_variant ret)
	{
		if (method == MethodName.RequestCompletion && args.Count == 0)
		{
			RequestCompletion();
			ret = default;
			return true;
		}
		return base.InvokeGodotClassMethod(in method, args, out ret);
	}

	[EditorBrowsable(EditorBrowsableState.Never)]
	protected override bool HasGodotClassMethod(in godot_string_name method)
	{
		if (method == MethodName.RequestCompletion)
		{
			return true;
		}
		return base.HasGodotClassMethod(in method);
	}

	[EditorBrowsable(EditorBrowsableState.Never)]
	protected override bool GetGodotClassPropertyValue(in godot_string_name name, out godot_variant value)
	{
		if (name == PropertyName.CodeEdit)
		{
			value = VariantUtils.CreateFrom(in CodeEdit);
			return true;
		}
		return base.GetGodotClassPropertyValue(in name, out value);
	}

	[EditorBrowsable(EditorBrowsableState.Never)]
	internal static List<PropertyInfo> GetGodotPropertyList()
	{
		return new List<PropertyInfo>
		{
			new PropertyInfo(Variant.Type.Object, PropertyName.CodeEdit, PropertyHint.None, "", PropertyUsageFlags.ScriptVariable, exported: false)
		};
	}

	[EditorBrowsable(EditorBrowsableState.Never)]
	protected override void SaveGodotObjectData(GodotSerializationInfo info)
	{
		base.SaveGodotObjectData(info);
	}

	[EditorBrowsable(EditorBrowsableState.Never)]
	protected override void RestoreGodotObjectData(GodotSerializationInfo info)
	{
		base.RestoreGodotObjectData(info);
	}
}
